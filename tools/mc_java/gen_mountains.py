"""Mountain ring around the Bin & Bo city (vanilla Java datapack generator).

Replaces the city-v2 mountains (cv2_5), which were 2x2 stepped columns of one
material and read as vertical stripes in the reference shots.  This version:
  * 1x1 columns with a smooth two-octave value-noise height field,
  * a ring profile that rises behind the wall and falls away outside, so there is
    no flat vertical outer face,
  * surface material by height and slope (grass/dirt on gentle slopes, mixed
    stone/andesite/tuff/gravel patches on cliffs, calcite + snow on peaks),
  * spruce/pine placed afterwards on gentle low slopes.

    python tools/mc_java/gen_mountains.py OUT_DIR    # writes mtn_0..3 + mtn_trees .mcfunction
In game:  /function binbo:mtn_0 ... /function binbo:mtn_3, then /function binbo:mtn_trees
"""
import math
import os
import sys

CX, CZ, G = 260, 60, -60          # city centre and the grass level the city stands on
R_IN, R_PEAK, R_OUT = 116, 127, 142
CLEAR_TOP = 0                      # old cv2_5 peaks stay below this
MAX_CMDS = 60000                   # vanilla maxCommandChainLength is 65536


def _hash(ix, iz, seed):
    h = (ix * 374761393 + iz * 668265263 + seed * 2147483647) & 0xFFFFFFFF
    h = ((h ^ (h >> 13)) * 1274126177) & 0xFFFFFFFF
    return ((h ^ (h >> 16)) & 0xFFFF) / 65535.0


def noise(x, z, scale, seed):
    """Smooth value noise in [0, 1]."""
    fx, fz = x / scale, z / scale
    ix, iz = math.floor(fx), math.floor(fz)
    tx, tz = fx - ix, fz - iz
    sx, sz = tx * tx * (3 - 2 * tx), tz * tz * (3 - 2 * tz)
    a, b = _hash(ix, iz, seed), _hash(ix + 1, iz, seed)
    c, d = _hash(ix, iz + 1, seed), _hash(ix + 1, iz + 1, seed)
    return (a + (b - a) * sx) + ((c + (d - c) * sx) - (a + (b - a) * sx)) * sz


def smooth(e0, e1, v):
    t = min(1.0, max(0.0, (v - e0) / (e1 - e0)))
    return t * t * (3 - 2 * t)


def height(x, z):
    """Blocks above G (0 = flat ground)."""
    r = math.hypot(x - CX, z - CZ)
    if r < R_IN or r > R_OUT:
        return 0
    ring = smooth(R_IN, R_PEAK - 3, r) * (1 - smooth(R_PEAK + 2, R_OUT, r))
    n = 0.65 * noise(x, z, 26, 11) + 0.35 * noise(x, z, 9, 23)
    return max(0, round(ring * (12 + 54 * n ** 1.6 + 6 * noise(x, z, 5, 37))))


def surface(x, z, h, slope):
    """(top block, three blocks under the top)."""
    y = G + h
    patch = noise(x, z, 6, 51)
    if y >= -22:
        return ('snow_block' if slope < 4 else 'calcite'), 'calcite'
    if slope >= 3:
        rock = ('stone', 'andesite', 'tuff', 'cobblestone', 'stone', 'andesite')[int(patch * 5.99)]
        if patch > 0.9:
            rock = 'gravel' if slope < 5 else 'stone'
        return rock, rock
    if y > -32 and patch > 0.62:
        return 'coarse_dirt', 'dirt'
    return ('podzol' if patch < 0.12 else 'grass_block'), 'dirt'


def columns():
    for x in range(CX - R_OUT, CX + R_OUT + 1):
        for z in range(CZ - R_OUT, CZ + R_OUT + 1):
            r = math.hypot(x - CX, z - CZ)
            if R_IN <= r <= R_OUT:
                yield x, z


def build():
    """-> (list of 4 quadrant command lists, tree command list)."""
    hmap = {(x, z): height(x, z) for x, z in columns()}
    quads = [[], [], [], []]
    trees = []
    for (x, z), h in hmap.items():
        q = (x >= CX) * 1 + (z >= CZ) * 2
        cmds = quads[q]
        nb = [hmap.get((x + dx, z + dz), 0) for dx, dz in ((1, 0), (-1, 0), (0, 1), (0, -1))]
        slope = max(abs(h - v) for v in nb)
        y = G + h
        cmds.append(f'fill {x} {max(y + 1, G + 1)} {z} {x} {CLEAR_TOP} {z} air')
        if h <= 0:
            continue
        top, under = surface(x, z, h, slope)
        if h > 4:
            cmds.append(f'fill {x} {G + 1} {z} {x} {y - 4} {z} stone')
        if h > 1:
            cmds.append(f'fill {x} {max(G + 1, y - 3)} {z} {x} {y - 1} {z} {under}')
        cmds.append(f'setblock {x} {y} {z} {top}')
        if top in ('grass_block', 'podzol') and slope <= 2 and y < -28 and _hash(x, z, 77) < 0.05:
            feat = 'spruce'  # 'pine' reads as a palm tuft from the city
            trees.append(f'place feature minecraft:{feat} {x} {y + 1} {z}')
    return quads, trees


def forceload():
    x0, x1, z0, z1 = CX - R_OUT, CX + R_OUT, CZ - R_OUT, CZ + R_OUT
    xm = (x0 + x1) // 2
    return [f'forceload add {x0} {z0} {xm} {z1}', f'forceload add {xm + 1} {z0} {x1} {z1}']


def write(out_dir):
    os.makedirs(out_dir, exist_ok=True)
    quads, trees = build()
    files = {}
    for i, q in enumerate(quads):
        files[f'mtn_{i}.mcfunction'] = forceload() + q
    files['mtn_trees.mcfunction'] = forceload() + trees
    for name, cmds in files.items():
        assert len(cmds) < MAX_CMDS, (name, len(cmds))
        with open(os.path.join(out_dir, name), 'w', encoding='utf-8') as f:
            f.write(f'# generated by tools/mc_java/gen_mountains.py\n' + '\n'.join(cmds) + '\n')
    return {n: len(c) for n, c in files.items()}


if __name__ == '__main__':
    print('MTN_OK', write(sys.argv[1] if len(sys.argv) > 1 else 'mtn_out'))
